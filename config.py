"""All settings for the departure board live here.

Change values in this file to adapt the board, nothing else should need editing.
"""

# --- Station and filtering ---------------------------------------------------

# Find a site id with:  python sl_api.py search "Sandsborg"
STATION_NAME = "Sandsborg"
SITE_ID = 9186

# Only show this kind of traffic (the API also returns BUS, TRAM, TRAIN, ...).
TRANSPORT_MODE = "METRO"

# SL's direction_code for the direction we want to show.
# Checked against the real API at Sandsborg (line 18):
#   1 = northbound, towards Gullmarsplan / T-Centralen (e.g. "Alvik", "Hässelby strand")
#   2 = southbound, towards Farsta strand
DIRECTION_CODE = 1

# --- Timing -----------------------------------------------------------------

FETCH_INTERVAL_SECONDS = 30   # how often we ask the API for new data
REQUEST_TIMEOUT_SECONDS = 10  # give up on a slow API call after this long
FRAMES_PER_SECOND = 30        # how often the screen is redrawn (higher = smoother scrolling)

# --- Layout and look ----------------------------------------------------------

PANEL_WIDTH = 64
PANEL_HEIGHT = 32
# Display mode (can also be chosen when starting: python main.py --mode 2)
#   1 = the next train in big text, the following trains scroll by in a ticker
#   2 = three still rows in smaller text, nothing moves except the minutes
DISPLAY_MODE = 1

# Mode 1: the bottom row scrolls the following departures right to left.
TICKER_SPEED = 10             # pixels per second (lower = slower)
TICKER_DEPARTURES = 3         # how many of the following departures scroll by
TICKER_BRIGHTNESS = 0.7       # the ticker row compared to the top row (0.7 = 30% dimmer)
TICKER_SMALL_TEXT = True      # smaller letters in the ticker (the mode 2 font), False = same as top row

# Mode 2: number of still rows.
MODE2_ROWS = 3

# SL-style fonts, generated by tools/make_sl_font.py
FONT_MODE1 = "fonts/sl-large.bdf"  # capitals 10 px tall
FONT_MODE2 = "fonts/sl-small.bdf"  # capitals 7 px tall
FONT_CLOCK = "fonts/9x18B.bdf"     # big clock shown when there are no departures

# Colors as (red, green, blue), 0-255.
TEXT_COLOR = (255, 150, 0)    # orange-yellow, like SL platform signs
WARNING_COLOR = (200, 0, 0)   # small dot shown when the API can't be reached

# Long destinations on the still rows are shortened like SL's signs do
# ("Hässelby strand" -> "Hässelby str."). Set to False to scroll them instead
# (mode 1 only; mode 2 always shortens so nothing moves).
SHORTEN_LONG_NAMES = True

# Show the line number ("18") on the still rows. Off by default to leave room
# for the destination: every metro at Sandsborg is line 18, and the ticker
# still shows it.
SHOW_LINE_NUMBER = False
ABBREVIATIONS = {             # whole words that may be shortened, tried first
    "strand": "str.",
    "centrum": "C",
}

SCROLL_SPEED = 12             # pixels per second for long destination names
SCROLL_PAUSE_SECONDS = 2      # pause before a long name starts scrolling

# --- Brightness and night mode ----------------------------------------------

BRIGHTNESS = 60               # 0-100

NIGHT_MODE_ENABLED = True
NIGHT_START = "23:00"         # 24h clock, local time
NIGHT_END = "06:00"
NIGHT_BRIGHTNESS = 10         # 0 = screen off, otherwise dimmed brightness (1-100)

# --- Morning message ---------------------------------------------------------

# A little message shown in the morning, one string per row (at most 3 rows).
# The letters, digits and . , : - / ' ( ) ? ! and ♥ are available.
# Set to [] to turn it off. Preview it with:  python demo.py --message
MORNING_MESSAGE = ["Godmorgon!", "Ha en fin dag ♥"]
MORNING_MESSAGE_DATE = "2026-11-26"  # only on this day ("YYYY-MM-DD"), None = every day
MORNING_MESSAGE_START = "05:45"   # show it between these times
MORNING_MESSAGE_END = "09:00"
MESSAGE_SECONDS = 30              # show the message this long ...
MESSAGE_EVERY_SECONDS = 30        # ... once every this many seconds (departures the rest).
                                  # The same value for both = the message all the time.

TIMEZONE = "Europe/Stockholm"  # the API returns local Stockholm times

# --- Hardware (only used on the Raspberry Pi) --------------------------------

HARDWARE_MAPPING = "regular"  # panel wired directly to the GPIO pins, no HAT
GPIO_SLOWDOWN = 2             # Pi 3 usually needs 1-2; raise if the image flickers/garbles
PWM_BITS = 11                 # lower (e.g. 7) reduces flicker at the cost of colors
DISABLE_HARDWARE_PULSING = False  # set True only if you can't turn off onboard audio

# The library normally drops root privileges after start. We keep them so the
# program can still read files in the home directory (fonts etc.).
DROP_PRIVILEGES = False
